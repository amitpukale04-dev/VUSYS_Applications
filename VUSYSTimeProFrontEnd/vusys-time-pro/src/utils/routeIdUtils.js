const ROUTE_ID_PREFIX = "timepro";
const ROUTE_ID_VERSION = "v1";

const toBase64Url = (value) =>
  window
    .btoa(String(value))
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/g, "");

const fromBase64Url = (value) => {
  const normalized = String(value || "")
    .replace(/-/g, "+")
    .replace(/_/g, "/");
  const padding = normalized.length % 4;
  const padded =
    padding === 0 ? normalized : normalized + "=".repeat(4 - padding);

  return window.atob(padded);
};

/**
 * Encodes a numeric route identifier so raw database IDs are not exposed
 * directly in the browser URL.
 */
export const encodeRouteId = (id) => {
  const normalizedId = Number(id);

  if (!Number.isInteger(normalizedId) || normalizedId <= 0) {
    return "";
  }

  return toBase64Url(
    `${ROUTE_ID_PREFIX}:${ROUTE_ID_VERSION}:${normalizedId}`,
  );
};

/**
 * Decodes an encoded route identifier back to its numeric ID.
 *
 * Numeric values are accepted as a backward-compatible fallback so existing
 * bookmarked URLs do not fail immediately after this change. All new
 * navigation generated by TimePro uses encodeRouteId().
 */
export const decodeRouteId = (encodedId) => {
  const rawValue = String(encodedId || "").trim();

  if (!rawValue) {
    return 0;
  }

  if (/^\d+$/.test(rawValue)) {
    const legacyId = Number(rawValue);
    return Number.isInteger(legacyId) && legacyId > 0 ? legacyId : 0;
  }

  try {
    const decoded = fromBase64Url(rawValue);
    const [prefix, version, idValue] = decoded.split(":");

    if (prefix !== ROUTE_ID_PREFIX || version !== ROUTE_ID_VERSION) {
      return 0;
    }

    const id = Number(idValue);
    return Number.isInteger(id) && id > 0 ? id : 0;
  } catch {
    return 0;
  }
};
