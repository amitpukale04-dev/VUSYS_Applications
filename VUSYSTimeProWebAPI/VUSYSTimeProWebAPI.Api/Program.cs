using VUSYSTimeProWebAPI.Api;
using VUSYSTimeProWebAPI.Api.Extensions;
using VUSYSTimeProWebAPI.Api.Helpers;
using VUSYSTimeProWebAPI.Api.Middlewares;
using VUSYSTimeProWebAPI.Application;
using VUSYSTimeProWebAPI.Application.Abstractions.Persistence;
using VUSYSTimeProWebAPI.Application.Common.Options;
using VUSYSTimeProWebAPI.Infrastructure;
using VUSYSTimeProWebAPI.Infrastructure.Common;

var builder = WebApplication.CreateBuilder(args);

// ----------------------------------------------------
// Layer registrations
// ----------------------------------------------------

builder.Services
    .AddApiServices(builder.Configuration, builder.Environment)
    .AddApplication()
    .AddInfrastructure(builder.Configuration, builder.Environment);

// ----------------------------------------------------
// JWT authentication and authorization
// ----------------------------------------------------

builder.Services.AddJwtAuthentication(builder.Configuration);

// ----------------------------------------------------
// Swagger
// ----------------------------------------------------

builder.Services.AddSwaggerDocumentation();

var app = builder.Build();

CommonHelper.Initialise(app.Services.GetRequiredService<MyApplicationKeysOptions>());

CommonHelper.GeminiAIInitialise(app.Services.GetRequiredService<GeminiAIKeysOptions>());

// ----------------------------------------------------
// Warm up ODBC database connection
// ----------------------------------------------------

await using (AsyncServiceScope scope = app.Services.CreateAsyncScope())
{
    IDatabaseWarmUpService databaseWarmUpService = scope.ServiceProvider.GetRequiredService<IDatabaseWarmUpService>();
    await databaseWarmUpService.WarmUpDatabaseConnectionAsync();
}

// ----------------------------------------------------
// Initialise static legacy helpers
// ----------------------------------------------------

HttpContextHelper.Configure(app.Services.GetRequiredService<IHttpContextAccessor>());

// ----------------------------------------------------
// log4net
// ----------------------------------------------------

app.ConfigureLog4Net();

// ----------------------------------------------------
// Swagger UI
// ----------------------------------------------------

// Swagger is enabled in all environments.
app.UseSwaggerDocumentation();

// ----------------------------------------------------
// HTTP pipeline
// ----------------------------------------------------

// Must remain first so that it can catch exceptions
// generated by all middleware below it.
app.UseMiddleware<GlobalErrorHandlingMiddleware>();
// Compress HTTP/HTTPS responses before they are sent to the client.
app.UseResponseCompression();
app.UseHttpsRedirection();
app.UseRouting();
app.UseCors(ApiCorsPolicy.PolicyName);

app.UseAuthentication();

// Authentication must execute first because this
// middleware reads claims from HttpContext.User.
app.UseMiddleware<UserContextMiddleware>();

// Validates the JWT against the token store and
// logs the API request body.
app.UseMiddleware<RequestLoggingMiddleware>();
app.UseAuthorization();
app.MapControllers();
app.Run();